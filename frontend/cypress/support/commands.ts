// Pour TypeScript, vous pouvez déclarer les commandes dans un fichier séparé
// Exemple: declare global { namespace Cypress { interface Chainable { login(email: string, password: string): Chainable<void> } } }

// Ajout d'une commande personnalisée pour la connexion
Cypress.Commands.add('login', (email: string, password: string) => {
  cy.visit('/login');
  cy.get('input[type="email"]').type(email);
  cy.get('input[type="password"]').type(password);
  cy.contains('button', 'Se connecter').click();
});
